import { createHash } from 'node:crypto'
import { readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath, URL } from 'node:url'

import tailwindcss from '@tailwindcss/vite'
import vue from '@vitejs/plugin-vue'
import type { Plugin } from 'vite'
import { defineConfig } from 'vitest/config'

/**
 * Offline support: after the build, write `sw.js` with the full list of built files. The service
 * worker precaches them on install and serves the app cache-first, so once loaded the editor
 * opens and works without a network connection.
 */
function offlineServiceWorker(): Plugin {
  let outDir = 'dist'
  return {
    name: 'kaat-offline-sw',
    apply: 'build',
    configResolved(c) {
      outDir = c.build.outDir
    },
    generateBundle(_, bundle) {
      const files = new Set<string>(Object.keys(bundle))
      const pub = fileURLToPath(new URL('./public', import.meta.url))
      const walk = (d: string) => {
        for (const n of readdirSync(d)) {
          const p = join(d, n)
          if (statSync(p).isDirectory()) walk(p)
          else files.add(relative(pub, p))
        }
      }
      try {
        walk(pub)
      } catch {
        // no public dir
      }
      files.delete('sw.js')
      const list = ['./', ...[...files].sort().map((f) => `./${f}`)]
      const version = createHash('sha256').update(list.join('\n')).digest('hex').slice(0, 12)
      void outDir
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: `// Generated by kaat-offline-sw. Precache-and-serve for offline use.
const CACHE = 'kaat-${version}'
const FILES = ${JSON.stringify(list)}
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()))
})
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('kaat-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  )
})
self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return
  if (req.mode === 'navigate') {
    e.respondWith(caches.match('./', { cacheName: CACHE }).then((r) => r || fetch(req)))
    return
  }
  e.respondWith(caches.match(req, { cacheName: CACHE, ignoreSearch: true }).then((r) => r || fetch(req)))
})
`,
      })
    },
  }
}

export default defineConfig({
  base: './',
  plugins: [vue(), tailwindcss(), offlineServiceWorker()],
  define: {
    __KAAT_BUILD__: JSON.stringify(new Date().toISOString().slice(0, 10)),
  },
  resolve: {
    alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) },
  },
  worker: { format: 'es' },
  build: { target: 'es2023', chunkSizeWarningLimit: 1500 },
  server: { port: 5174 },
  preview: { port: 4174 },
  test: {
    include: ['src/**/*.test.ts'],
    environment: 'jsdom',
  },
})
